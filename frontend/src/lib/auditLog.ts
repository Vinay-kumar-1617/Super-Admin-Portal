export type AuditLogsResult = {
  records: AuditLogRecord[]
  total: number
  page: number
  pageSize: number
  pageCount: number
}

export function loadDemoAuditLogs(filters: AuditLogFilters = {}, scope?: AuditScope): AuditLogsResult {
  const resolvedScope = scope ?? resolveAuditScope({
    roleKey: 'super-admin',
    scopeType: 'national',
    scopeId: null,
  })
  let list = filterAuditLogsByScope(DEMO_AUDIT_LOGS, resolvedScope)
  list = list.filter((log) => matchAuditLog(log, filters))
  list.sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime())
  const page = filters.page ?? 1
  const pageSize = filters.pageSize ?? 10
  const paged = paginate(list, page, pageSize)
  return {
    records: paged.items,
    total: paged.total,
    page: paged.page,
    pageSize: paged.pageSize,
    pageCount: paged.pageCount,
  }
}


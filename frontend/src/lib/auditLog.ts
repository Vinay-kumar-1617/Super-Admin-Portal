export async function fetchAuditLogs(filters: AuditLogFilters = {}, profile: AuditProfile): Promise<AuditLogsResult> {
  const scope = resolveAuditScope({
    roleKey: profile.roleKey,
    scopeType: profile.scopeType,
    scopeId: profile.scopeId,
  })
  if (!supabase) {
    return loadDemoAuditLogs(filters, scope)
  }
  let query = supabase
    .from('audit_logs')
    .select('*', { count: 'exact' })
    .order('created_at', { ascending: false })
  if (!scope.allStates && scope.stateId) {
    query = query.eq('state_id', scope.stateId)
  }
  if (!scope.allStates && scope.cityName) {
    query = query.eq('city_name', scope.cityName)
  }
  if (filters.action && filters.action !== 'all') {
    query = query.eq('action', filters.action)
  }
  if (filters.outcome && filters.outcome !== 'all') {
    query = query.eq('outcome', filters.outcome)
  }
  if (filters.date) {
    query = query.gte('created_at', `${filters.date}T00:00:00`).lte('created_at', `${filters.date}T23:59:59.999`)
  }
  const page = filters.page ?? 1
  const pageSize = filters.pageSize ?? 10
  const from = (page - 1) * pageSize
  const to = from + pageSize - 1
  query = query.range(from, to)
  const { data, error, count } = await query
  if (error || !data) {
    return loadDemoAuditLogs(filters, scope)
  }
  const records = (data as unknown as AuditLogRow[]).map((row) => ({
    id: row.id,
    createdAt: row.created_at,
    actorId: row.actor_id,
    actorEmail: row.actor_email,
    actorName: row.actor_name,
    actorRole: (row.actor_role ?? null) as RoleKey | string | null,
    action: row.action as AuditLogRecord['action'],
    actionLabel: row.action_label,
    entityType: row.entity_type,
    entityId: row.entity_id,
    entityLabel: row.entity_label,
    stateId: row.state_id,
    cityId: row.city_id,
    zoneId: row.zone_id,
    stateName: row.state_name,
    cityName: row.city_name,
    zoneName: row.zone_name,
    previousValues: row.previous_values,
    newValues: row.new_values,
    outcome: row.outcome as AuditLogRecord['outcome'],
    ipAddress: row.ip_address,
    userAgent: row.user_agent,
    metadata: row.metadata,
  }))
  const total = count ?? records.length
  const pageCount = Math.max(1, Math.ceil(total / pageSize))
  return { records, total, page, pageSize, pageCount }
}

export function exportAuditLogsCsv(logs: AuditLogRecord[]): string {
  return auditLogsToCsv(logs)
}
